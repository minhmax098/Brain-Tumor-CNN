# Get all image files from /content/
all_files = [f for f in os.listdir('/content/') if f.lower().endswith(('.png', '.jpg', '.jpeg', '.gif'))]

tumor_files = []
normal_files = []

for file_name in all_files:
    # Improved logic to classify based on content of filename
    if 'y' in file_name.lower() or 'yes' in file_name.lower():
        tumor_files.append(file_name)
    elif 'n' in file_name.lower() or 'no' in file_name.lower():
        normal_files.append(file_name)

# Initialize empty lists for splits
train_tumor, test_tumor = [], []
train_normal, test_normal = [], []

# Perform split only if there are files in the category
if tumor_files:
    train_tumor, test_tumor = train_test_split(tumor_files, test_size=0.2, random_state=42)
else:
    print("Warning: No 'tumor' images found based on filename pattern (containing 'y' or 'yes').")

if normal_files:
    train_normal, test_normal = train_test_split(normal_files, test_size=0.2, random_state=42)
else:
    print("Warning: No 'normal' images found based on filename pattern (containing 'n' or 'no').")

# Function to move files
def move_files(file_list, destination_folder):
    for file_name in file_list:
        shutil.move(os.path.join('/content/', file_name), destination_folder)

# Move tumor files (only if lists are not empty)
if train_tumor:
    move_files(train_tumor, os.path.join(train_dir, "tumor"))
if test_tumor:
    move_files(test_tumor, os.path.join(test_dir, "tumor"))

# Move normal files (only if lists are not empty)
if train_normal:
    move_files(train_normal, os.path.join(train_dir, "normal"))
