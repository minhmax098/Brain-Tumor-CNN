train_dir = "/content/brain_tumor_dataset/train"
test_dir = "/content/brain_tumor_dataset/test"

# Create base directory
if not os.path.exists("/content/brain_tumor_dataset"):
    os.makedirs("/content/brain_tumor_dataset")

# Create train and test directories for both classes
os.makedirs(os.path.join(train_dir, "tumor"), exist_ok=True)
